def test_hand_edited_file_is_refused(engine_with_schema, tmp_path) -> None:  # type: ignore[no-untyped-def]
    """A hand edit of a generated file is drift, not input."""
    factory = make_session_factory(engine_with_schema)
    with transactional(factory) as session:
        pid = _seed(session, tmp_path)
        s = _create(session, pid)
        _export(session, pid, tmp_path)

        target = _target(tmp_path)
        target.write_text(target.read_text() + "\nhand-written line\n")

        scenario_service.update(
            session,
            project_id=pid,
            scenario_id=s.scenario_id,
            author="human:test",
            title="Renamed after a hand edit",
        )
        with pytest.raises(ExportGuardError):
            _export(session, pid, tmp_path)


def test_hand_edit_shows_up_as_drift(engine_with_schema, tmp_path) -> None:  # type: ignore[no-untyped-def]
    factory = make_session_factory(engine_with_schema)
    with transactional(factory) as session:
        pid = _seed(session, tmp_path)
        _create(session, pid)
        result = _export(session, pid, tmp_path)

        target = _target(tmp_path)
        target.write_text(target.read_text() + "\nhand-written line\n")

        report = projection_service.detect_drift(session, result.document_id, root_path=tmp_path)
    assert report.status.value == "edited_in_place"


