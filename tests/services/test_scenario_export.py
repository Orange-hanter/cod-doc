"""TSC-005: scenario group → markdown projection.

Covers the three things that make the projection trustworthy: it is
idempotent, a hand edit is refused rather than overwritten, and a group whose
scenarios were all retired keeps its document.
"""

from __future__ import annotations

from datetime import UTC, datetime
from typing import TYPE_CHECKING

import pytest

from cod_doc.domain.entities import (
    ScenarioKind,
    ScenarioLinkKind,
    ScenarioRelation,
)
from cod_doc.infra.db import make_session_factory, transactional
from cod_doc.infra.models import ProjectModel
from cod_doc.services import projection_service, scenario_service
from cod_doc.services.projection_service import ExportGuardError

if TYPE_CHECKING:
    from pathlib import Path

GROUP = "plan-management"


def _seed(session, root: Path) -> int:  # type: ignore[no-untyped-def]
    now = datetime.now(UTC)
    proj = ProjectModel(slug="scn", title="P", root_path=str(root), config_json={})
    proj.created = now
    proj.updated = now
    session.add(proj)
    session.flush()
    return proj.row_id


def _create(session, pid: int, **kw):  # type: ignore[no-untyped-def]
    params = {
        "title": "Plan progress recomputes after a task completes",
        "kind": ScenarioKind.HAPPY_PATH,
        "group_key": GROUP,
        "preconditions": "A plan with one open task exists.",
        "expected": "plan_progress reports one task done.",
        "steps": ["Complete the task", "Read the plan progress"],
        "author": "human:test",
    }
    params.update(kw)
    return scenario_service.create(session, project_id=pid, **params)


def _export(session, pid: int, root: Path):  # type: ignore[no-untyped-def]
    return scenario_service.export_group(
        session,
        project_id=pid,
        group_key=GROUP,
        root_path=root,
        author="human:test",
        own_checkout_only=False,
    )


def _target(root: Path) -> Path:
    return root / "docs" / "system" / "scenarios" / f"{GROUP}.md"


# --------------------------------------------------------------------------- #
# first export                                                                 #
# --------------------------------------------------------------------------- #


def test_export_writes_file_with_scenario_sections(engine_with_schema, tmp_path) -> None:  # type: ignore[no-untyped-def]
    factory = make_session_factory(engine_with_schema)
    with transactional(factory) as session:
        pid = _seed(session, tmp_path)
        _create(session, pid)
        result = _export(session, pid, tmp_path)

    assert result.written is True
    body = _target(tmp_path).read_text()
    assert "## Overview" in body
    assert "## SCN-001 — Plan progress recomputes after a task completes" in body
    assert "### Preconditions" in body
    assert "1. Complete the task" in body
    assert "generated by scenario_service" in body


def test_export_records_kind_counts(engine_with_schema, tmp_path) -> None:  # type: ignore[no-untyped-def]
    factory = make_session_factory(engine_with_schema)
    with transactional(factory) as session:
        pid = _seed(session, tmp_path)
        _create(session, pid, kind=ScenarioKind.HAPPY_PATH)
        _create(session, pid, kind=ScenarioKind.ERROR_PATH)
        _export(session, pid, tmp_path)

    body = _target(tmp_path).read_text()
    assert "| `happy_path` | 1 |" in body
    assert "| `error_path` | 1 |" in body
    assert "| **total** | **2** |" in body


def test_links_are_rendered(engine_with_schema, tmp_path) -> None:  # type: ignore[no-untyped-def]
    factory = make_session_factory(engine_with_schema)
    with transactional(factory) as session:
        pid = _seed(session, tmp_path)
        s = _create(session, pid)
        scenario_service.link(
            session,
            project_id=pid,
            scenario_id=s.scenario_id,
            to_kind=ScenarioLinkKind.CRITERION,
            to_ref="US-013#2",
            relation=ScenarioRelation.VERIFIES,
            author="human:test",
        )
        _export(session, pid, tmp_path)

    assert "`verifies` → `criterion:US-013#2`" in _target(tmp_path).read_text()


