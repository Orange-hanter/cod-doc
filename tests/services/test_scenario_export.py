def test_retired_scenario_section_is_removed(engine_with_schema, tmp_path) -> None:  # type: ignore[no-untyped-def]
    factory = make_session_factory(engine_with_schema)
    with transactional(factory) as session:
        pid = _seed(session, tmp_path)
        first = _create(session, pid)
        _create(session, pid, kind=ScenarioKind.ERROR_PATH, title="Second")
        _export(session, pid, tmp_path)

        scenario_service.retire(
            session, project_id=pid, scenario_id=first.scenario_id, author="human:test"
        )
        _export(session, pid, tmp_path)

    body = _target(tmp_path).read_text()
    assert "## SCN-001" not in body
    assert "## SCN-002 — Second" in body


def test_group_with_everything_retired_keeps_document(engine_with_schema, tmp_path) -> None:  # type: ignore[no-untyped-def]
    """Deleting the document would break links and registries — keep the Overview."""
    factory = make_session_factory(engine_with_schema)
    with transactional(factory) as session:
        pid = _seed(session, tmp_path)
        s = _create(session, pid)
        _export(session, pid, tmp_path)
        scenario_service.retire(
            session, project_id=pid, scenario_id=s.scenario_id, author="human:test"
        )
        _export(session, pid, tmp_path)

    body = _target(tmp_path).read_text()
    assert "## Overview" in body
    assert "| **total** | **0** |" in body
    assert "## SCN-001" not in body


