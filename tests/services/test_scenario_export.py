def test_export_all_covers_every_group(engine_with_schema, tmp_path) -> None:  # type: ignore[no-untyped-def]
    factory = make_session_factory(engine_with_schema)
    with transactional(factory) as session:
        pid = _seed(session, tmp_path)
        _create(session, pid)
        _create(session, pid, group_key="doc-evolution", title="Drift is detected")
        results = scenario_service.export_all(
            session,
            project_id=pid,
            root_path=tmp_path,
            author="human:test",
            own_checkout_only=False,
        )

    assert len(results) == 2
    assert (tmp_path / "docs/system/scenarios/doc-evolution.md").exists()
    assert _target(tmp_path).exists()


def test_export_emits_activity_event(engine_with_schema, tmp_path) -> None:  # type: ignore[no-untyped-def]
    from sqlalchemy import select

    from cod_doc.infra.models import ActivityEventModel

    factory = make_session_factory(engine_with_schema)
    with transactional(factory) as session:
        pid = _seed(session, tmp_path)
        _create(session, pid)
        _export(session, pid, tmp_path)
        session.flush()
        kinds = [
            e.kind
            for e in session.execute(
                select(ActivityEventModel).where(ActivityEventModel.scope_kind == "scenario_group")
            ).scalars()
        ]
    assert kinds == ["scenario.exported"]
